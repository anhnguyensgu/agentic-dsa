// External courses `langlings add` can fetch. There are two kinds: "git"
// courses are cloned, "cli" courses are created by the course's own tool.
// Either way the fetch command creates a folder named after the course, which
// is then imported. The third kind, built-in courses, ship inside langlings
// (see builtin.go).
var courses = map[string]struct {
	kind  string
	fetch []string
	help  string // what to install if fetching fails
}{
	"ziglings":  {"git", []string{"git", "clone", "https://codeberg.org/ziglings/exercises.git", "ziglings"}, "it needs git"},
	"rustlings": {"cli", []string{"rustlings", "init"}, "it needs the rustlings CLI: cargo install rustlings"},
}

// addCourse sets up a course next to tracks/, so learning a language starts
// with one command. A course folder that's already there is kept as it is.
func addCourse(name string) error {
	w, err := openOrCreateWorkspace()
	if err != nil {
		return err
	}
	if slices.Contains(builtinCourses(), name) {
		if err := addBuiltin(w, name); err != nil {
			return err
		}
		if w, err = openWorkspace(); err != nil {
			return err
		}
		reportTrack(w, w.tracks[name])
	} else {
		c, ok := courses[name]
		if !ok {
			return fmt.Errorf("don't know a course called %q\n\n%s", name, courseList())
		}
		dir := filepath.Join(w.dir, name)
		if _, err := os.Stat(dir); err != nil {
			fmt.Printf("getting %s: %s\n", name, strings.Join(c.fetch, " "))
			cmd := exec.Command(c.fetch[0], c.fetch[1:]...)
			cmd.Dir = w.dir
			cmd.Stderr = os.Stderr // stdout is dropped: rustlings init prints "now run rustlings"
			if err := cmd.Run(); err != nil {
				return fmt.Errorf("getting %s failed (%s): %w", name, c.help, err)
			}
		}
		if err := importCourse(name, dir); err != nil {
			return err
		}
	}
	fmt.Printf("start with: langlings %s\n", name)
	return nil
}

func courseList() string {
	var b strings.Builder
	b.WriteString("courses (langlings add NAME):\n")
	for _, name := range builtinCourses() {
		fmt.Fprintf(&b, "  %-12s built in\n", name)
	}
	names := make([]string, 0, len(courses))
	for name := range courses {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		c := courses[name]
		fmt.Fprintf(&b, "  %-12s %s: %s\n", name, c.kind, strings.Join(c.fetch, " "))
	}
	return b.String()
}

// reportTrack says what a new track holds, and whether the language's tool
// is installed.
func reportTrack(w *Workspace, t *Track) {
	fmt.Printf("wrote tracks/%s.toml: %d exercises, %d already done\n", t.id, len(t.Exercises), w.progress.count(t))
	if tool := strings.Fields(t.Run); len(tool) > 0 {
		if _, err := exec.LookPath(tool[0]); err != nil {
			fmt.Fprintf(os.Stderr, "note: %s isn't installed, so exercises can't run until it is\n", tool[0])
		}
	}
}

func openOrCreateWorkspace() (*Workspace, error) {
	if w, err := openWorkspace(); err == nil {
		return w, nil
	}
	if err := os.Mkdir("tracks", 0o755); err != nil {
		return nil, err
	}
	return openWorkspace()
}

// importCourse writes tracks/<kind>.toml pointing at an existing course
// folder. Nothing in that folder is moved or changed, so it can still be
// updated from upstream.
func importCourse(kind, dir string) error {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return err
	}
	w, err := openOrCreateWorkspace()
	if err != nil {
		return err
	}

	var t *Track
	var done []string
	switch kind {
	case "rustlings":
		t, done, err = importRustlings(abs)
	case "ziglings":
		t, err = importZiglings(abs)
	default:
		return fmt.Errorf("don't know how to import %q (try rustlings or ziglings)", kind)
	}
	if err != nil {
		return err
	}
	t.id = kind
	if t.Root, err = filepath.Rel(w.tracksDir(), abs); err != nil {
		return err
	}

	path := filepath.Join(w.tracksDir(), kind+".toml")
	f, err := os.Create(path)
	if err != nil {
		return err
	}
	defer f.Close()
	fmt.Fprintf(f, "# Generated by `langlings import %s %s`. Re-run it to refresh.\n\n", kind, dir)
	writeTrack(f, t)

	// Carry over progress the course already tracked itself.
	for _, name := range done {
		if t.find(name) != nil {
			w.progress.setDone(kind, name, true)
		}
	}
	reportTrack(w, t)
	return w.progress.save()
}

var cargoBin = regexp.MustCompile(`\{\s*name\s*=\s*"([^"]+)",\s*path\s*=\s*"(exercises/[^"]+)"`)

// importRustlings reads the exercise order from Cargo.toml (it lists every
// exercise as a bin, in course order) and progress from .rustlings-state.txt.
func importRustlings(dir string) (*Track, []string, error) {
	cargo, err := os.ReadFile(filepath.Join(dir, "Cargo.toml"))
	if err != nil {
		return nil, nil, err
	}
	t := &Track{
		Run:  "cargo run -q --bin {name}",
		Test: "cargo test -q --bin {name}",
	}
	for _, m := range cargoBin.FindAllStringSubmatch(string(cargo), -1) {
		ex := Exercise{Name: m[1], File: m[2]}
		src, err := os.ReadFile(filepath.Join(dir, ex.File))
		if err != nil {
			return nil, nil, err
		}
		if strings.Contains(string(src), "#[cfg(test)]") {
			ex.Mode = "test"
		}
		if strings.Contains(ex.File, "clippy") {
			// Clippy exercises pass only when clippy has nothing to say.
			ex.Cmd = "cargo clippy -q --bin {name} -- -D warnings && cargo run -q --bin {name}"
		}
		readme := filepath.Join(filepath.Dir(ex.File), "README.md")
		if _, err := os.Stat(filepath.Join(dir, readme)); err == nil {
			ex.Readme = readme
		}
		t.Exercises = append(t.Exercises, ex)
	}
	if len(t.Exercises) == 0 {
		return nil, nil, fmt.Errorf("no exercises found in %s/Cargo.toml", dir)
	}

	hints, err := rustlingsHints(dir)
	if err != nil {
		fmt.Fprintf(os.Stderr, "note: importing without hints (%v)\n", err)
	}
	for i := range t.Exercises {
		t.Exercises[i].Hint = hints[t.Exercises[i].Name]
	}

	// The state file is a header, the current exercise, then finished ones.
	var done []string
	if f, err := os.Open(filepath.Join(dir, ".rustlings-state.txt")); err == nil {
		defer f.Close()
		sc := bufio.NewScanner(f)
		for i := 0; sc.Scan(); i++ {
			if line := strings.TrimSpace(sc.Text()); i >= 4 && line != "" {
				done = append(done, line)
			}
		}
	}
	return t, done, nil
}

// rustlingsHints reads the hints rustlings keeps inside its binary. They come
// from info.toml in the course folder if you put one there, otherwise from
// the copy on GitHub matching the installed rustlings version.
func rustlingsHints(dir string) (map[string]string, error) {
	data, err := os.ReadFile(filepath.Join(dir, "info.toml"))
	if err != nil {
		if data, err = fetchRustlingsInfo(); err != nil {
			return nil, err
		}
	}
	var info struct {
		Exercises []struct {
			Name string `toml:"name"`
			Hint string `toml:"hint"`
		} `toml:"exercises"`
	}
	if _, err := toml.Decode(string(data), &info); err != nil {
		return nil, err
	}
	hints := map[string]string{}
	for _, ex := range info.Exercises {
		hints[ex.Name] = ex.Hint
	}
	return hints, nil
}

func fetchRustlingsInfo() ([]byte, error) {
	ref := "main"
	if out, err := exec.Command("rustlings", "--version").Output(); err == nil {
		if f := strings.Fields(string(out)); len(f) == 2 {
			ref = "v" + f[1] // "rustlings 6.5.0" -> tag v6.5.0
		}
	}
	url := "https://raw.githubusercontent.com/rust-lang/rustlings/" + ref + "/rustlings-macros/info.toml"
	client := http.Client{Timeout: 15 * time.Second}
	resp, err := client.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// importZiglings parses ziglings' exercise list, where each entry has its
// expected output and hint.
func importZiglings(dir string) (*Track, error) {
	list, err := findExerciseList(dir)
	if err != nil {
		return nil, err
	}
	warnOldZig(dir)

	t := &Track{
		Run:    "zig run {file}",
		Test:   "zig test {file}",
		Stream: "stderr", // std.debug.print writes to stderr
	}
	var entry map[string]string
	var multiKey string // set while reading a \\ multi-line string
	var multi []string

	lines := strings.Split(list, "\n")[1:]
	for _, raw := range lines {
		line := strings.TrimSpace(raw)
		if multiKey != "" {
			if strings.HasPrefix(line, `\\`) {
				multi = append(multi, line[2:])
				continue
			}
			entry[multiKey] = strings.Join(multi, "\n")
			multiKey, multi = "", nil
		}
		switch {
		case line == "};":
			return t, nil
		case strings.HasPrefix(line, ".{"):
			entry = map[string]string{}
			line = line[2:]
		case entry == nil:
			continue
		}
		var closed bool
		multiKey, closed = parseFields(line, entry)
		if closed {
			t.Exercises = append(t.Exercises, zigExercise(entry))
			entry = nil
		}
	}
	return nil, fmt.Errorf("unterminated exercise list in %s", dir)
}

// findExerciseList returns ziglings' exercise list, from `const exercises`
// on. It used to be in build.zig and later moved to rivendell/elrond.zig, so
// every .zig file outside the exercises is searched.
func findExerciseList(dir string) (string, error) {
	const marker = "const exercises = [_]Exercise{"
	var list string
	filepath.WalkDir(dir, func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return nil
		}
		if d.IsDir() {
			switch d.Name() {
			case "exercises", "patches", ".git", ".zig-cache", "zig-out":
				return filepath.SkipDir
			}
			return nil
		}
		if src, err := os.ReadFile(path); err == nil && strings.HasSuffix(path, ".zig") {
			if i := strings.Index(string(src), marker); i >= 0 {
				list = string(src[i:])
				return filepath.SkipAll
			}
		}
		return nil
	})
	if list == "" {
		return "", fmt.Errorf("no exercise list (%s) in any .zig file under %s", marker, dir)
	}
	return list, nil
}

var requiredZig = regexp.MustCompile(`required_zig = "([^"]+)"`)

// warnOldZig says so when the installed Zig is older than the course needs.
// langlings runs `zig run` directly, which skips the version check ziglings
// does in its own build.zig.
func warnOldZig(dir string) {
	src, _ := os.ReadFile(filepath.Join(dir, "build.zig"))
	m := requiredZig.FindSubmatch(src)
	out, err := exec.Command("zig", "version").Output()
	if m == nil || err != nil {
		return
	}
	need, have := string(m[1]), strings.TrimSpace(string(out))
	if semver.Compare("v"+have, "v"+need) < 0 {
		fmt.Fprintf(os.Stderr, "note: this ziglings needs Zig %s or newer, but you have %s;\n"+
			"      exercises may fail to compile until you update Zig (https://ziglang.org/download/)\n", need, have)
	}
}

// parseFields reads `.key = value,` pairs from one line into e. It reports
// the key of a \\ string that continues on the next lines, and whether the
// line closes the entry.
func parseFields(s string, e map[string]string) (multiKey string, closed bool) {
	for {
		s = strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(s), ","))
		switch {
		case strings.HasPrefix(s, "}"):
			return "", true
		case !strings.HasPrefix(s, "."):
			return "", false // empty, or a comment
		}
		key, rhs, _ := strings.Cut(s[1:], "=")
		key, rhs = strings.TrimSpace(key), strings.TrimSpace(rhs)
		if rhs == "" {
			return key, false
		}
		val, n := zigValue(rhs)
		e[key] = val
		s = rhs[n:]
	}
}

func zigExercise(e map[string]string) Exercise {
	ex := Exercise{
		Name:   strings.TrimSuffix(e["main_file"], ".zig"),
		File:   "exercises/" + e["main_file"],
		Expect: e["output"],
		Hint:   e["hint"],
		Skip:   e["skip"] == "true",
	}
	if e["check_stdout"] == "true" {
		ex.Stream = "stdout"
	}
	if e["link_libc"] == "true" {
		ex.Cmd = "zig run -lc -fllvm {file}"
	}
	if e["kind"] == `.@"test"` {
		ex.Mode, ex.Expect = "test", ""
	}
	if e["timestamp"] == "true" {
		// The output contains the current time, which can't be matched exactly.
		ex.Expect = ""
	}
	if e["skip_hint"] != "" {
		ex.Hint = strings.TrimSpace(ex.Hint + "\n" + e["skip_hint"])
	}
	return ex
}

// zigValue reads one value from the start of v: a "string" (unescaped) or a
// bare word like true or .@"test". It returns the value and how many bytes
// of v it used.
func zigValue(v string) (string, int) {
	if strings.HasPrefix(v, `"`) {
		for i := 1; i < len(v); i++ {
			if v[i] == '\\' {
				i++
			} else if v[i] == '"' {
				if s, err := strconv.Unquote(v[:i+1]); err == nil {
					return s, i + 1
				}
				return v[1:i], i + 1
			}
		}
	}
	end := strings.IndexAny(v, ",}")
	if end < 0 {
		end = len(v)
	}
	return strings.TrimSpace(v[:end]), end
}

// writeTrack writes a track file by hand so that hints and expected output
// stay readable multi-line strings.
func writeTrack(w io.Writer, t *Track) {
	field := func(key, val string) {
		if val != "" {
			fmt.Fprintf(w, "%s = %s\n", key, tomlString(val))
		}
	}
	field("root", t.Root)
	field("run", t.Run)
	field("test", t.Test)
	field("stream", t.Stream)
	for _, ex := range t.Exercises {
		fmt.Fprint(w, "\n[[exercise]]\n")
		field("name", ex.Name)
		field("file", ex.File)
		field("mode", ex.Mode)
		field("cmd", ex.Cmd)
		field("stream", ex.Stream)
		field("readme", ex.Readme)
		field("expect", ex.Expect)
		field("hint", ex.Hint)
		if ex.Skip {
			fmt.Fprint(w, "skip = true\n")
		}
	}
}

func tomlString(s string) string {
	if strings.Contains(s, "\n") {
		return "\"\"\"\n" + strings.NewReplacer(`\`, `\\`, `"""`, `\"""`).Replace(s) + `"""`
	}
	return `"` + strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\t", `\t`, "\r", `\r`).Replace(s) + `"`
}
